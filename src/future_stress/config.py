GYEONGGI_FLOW_MONTHS = [202601, 202602, 202603]


def months_ending(end_month, length=ANALYSIS_LENGTH):
    """end_month에서 거꾸로 length개월 (달력 기준으로 연속). 예: months_ending(202602, 3) → [202512, 202601, 202602]"""
    index = (end_month // 100) * 12 + (end_month % 100 - 1)
    return [(i // 12) * 100 + i % 12 + 1 for i in range(index - length + 1, index + 1)]

