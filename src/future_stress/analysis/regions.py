# 원천 데이터의 오타 · 표기 차이 보정
REGION_NAME_FIXES = {"연천시": "연천군"}


def to_parent_city(region_name):
    """'수원시 장안구' → '수원시'처럼 일반구를 상위 시로 묶습니다.

    규칙: 공백으로 나눈 첫 단어가 '시'로 끝나고 뒤에 단어가 더 있으면 첫 단어만 사용합니다.
    '가평군', '과천시'처럼 한 단어인 지역은 그대로 둡니다.
    """
    parts = str(region_name).split()
    if len(parts) >= 2 and parts[0].endswith("시"):
        return parts[0]
    return region_name


def fix_region_name(region_name):
    """원천 데이터의 지역명 오타를 고칩니다 (예: 연천시 → 연천군)."""
    return REGION_NAME_FIXES.get(region_name, region_name)
